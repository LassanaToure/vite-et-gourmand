        <h1 id="cgv-title">Conditions Générales de Vente</h1>

        <section>
            <h2>Article 1 — Objet</h2>
            <p>Les présentes Conditions Générales de Vente (CGV) régissent les relations contractuelles entre la société <strong>Vite &amp; Gourmand SARL</strong> (ci-après « le Prestataire ») et tout client (particulier ou professionnel) passant commande via le site vitegourmand.fr ou par tout autre moyen.</p>
        </section>

        <section>
            <h2>Article 2 — Commandes</h2>
            <p>Toute commande est ferme et définitive à réception du bon de commande signé accompagné du versement d'un acompte de 30 % du montant total TTC. Les commandes doivent être passées selon le délai minimum indiqué sur chaque fiche menu (en général entre 3 et 14 jours avant la date de l'événement).</p>
            <p>Vite &amp; Gourmand se réserve le droit de refuser toute commande dont le délai n'est pas respecté.</p>
        </section>

        <section>
            <h2>Article 3 — Tarifs</h2>
            <p>Les prix sont indiqués en euros TTC par personne, sauf mention contraire. Ils sont susceptibles d'être modifiés à tout moment ; les prix applicables sont ceux en vigueur à la date de la commande.</p>
            <p>Vite &amp; Gourmand se réserve le droit d'appliquer une majoration en cas de commande inférieure au nombre de personnes minimum indiqué.</p>
        </section>

        <section>
            <h2>Article 4 — Livraison</h2>
            <p>La livraison est <strong>incluse dans Bordeaux intramuros</strong> (périmètre délimité par le boulevard de ceinture). Au-delà de ce périmètre, des frais de livraison s'appliquent selon le barème suivant :</p>
            <ul>
                <li>Forfait de départ : <strong>5,00 €</strong></li>
                <li>Frais kilométriques : <strong>0,59 €/km</strong> (distance aller simple depuis Bordeaux intramuros)</li>
            </ul>
            <p>Les horaires de livraison sont convenus lors de la validation de la commande. Tout retard lié à des circonstances extérieures (météo, trafic) ne pourra engager la responsabilité de Vite &amp; Gourmand.</p>
        </section>

        <section>
            <h2>Article 5 — Matériel</h2>
            <p>Le matériel fourni par Vite &amp; Gourmand (plats, couverts, contenants isothermes) reste la propriété du Prestataire. Il doit être restitué propre et en bon état dans un délai de <strong>10 jours</strong> suivant la date de l'événement.</p>
            <p>En cas de non-restitution ou de détérioration grave du matériel au-delà du délai imparti, une pénalité forfaitaire de <strong>600,00 €</strong> sera facturée au client.</p>
        </section>

        <section>
            <h2>Article 6 — Annulation</h2>
            <p>Toute annulation doit être communiquée par écrit à l'adresse <a href="mailto:contact@vitegourmand.fr">contact@vitegourmand.fr</a>. Le remboursement de l'acompte est conditionné au délai d'annulation :</p>
            <ul>
                <li>Plus de 15 jours avant l'événement : remboursement intégral</li>
                <li>Entre 8 et 15 jours : 50 % de l'acompte retenu</li>
                <li>Moins de 8 jours : acompte intégralement retenu</li>
            </ul>
        </section>

        <section>
            <h2>Article 7 — Allergènes</h2>
            <p>Vite &amp; Gourmand s'engage à indiquer les principaux allergènes présents dans chaque plat. Il appartient toutefois au client de vérifier la composition des menus et d'informer le Prestataire de toute allergie grave avant la commande. La responsabilité de Vite &amp; Gourmand ne pourra être engagée en l'absence de signalement préalable.</p>
        </section>

        <section>
            <h2>Article 8 — Litiges</h2>
            <p>En cas de litige, les parties s'engagent à rechercher une solution amiable avant tout recours judiciaire. À défaut d'accord, les tribunaux de Bordeaux sont compétents.</p>
        </section>

        <p class="prose__note">CGV mises à jour le 1er janvier 2026.</p>
    </div>
</article>
